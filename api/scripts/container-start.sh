#!/bin/sh
#
# إقلاع الخادم في حاويته (‎api/Dockerfile‎): يتأكد من قرص الصور، ثم يرحّل
# القاعدة ويعبّئها، ويسحب صور الخادم القديم إن طُلب، ثم يشغّل الخادم.
set -e

# ── قرص الصور ─────────────────────────────────────────────────────
# بلا قرصٍ دائم تُكتب الصور داخل الحاوية وتُمحى مع أول نشرٍ لاحق، بلا خطأٍ
# يُرى. فخيرٌ ألّا يقلع الخادم أصلاً من أن يفقدها بصمت: المجلّد أو أحد آبائه
# يجب أن يكون نقطة تركيب
dir="${UPLOAD_DIR:?UPLOAD_DIR غير معيَّن}"
mounted=""
while [ "$dir" != / ] && [ "$dir" != . ]; do
  if awk -v d="$dir" '$5 == d { found = 1 } END { exit !found }' /proc/self/mountinfo; then
    mounted=yes
    break
  fi
  dir=$(dirname "$dir")
done
if [ -z "$mounted" ]; then
  echo "لا قرص دائماً للصور: أضف في Railway قرصاً (Volume) مساره $UPLOAD_DIR ثم أعد النشر" >&2
  exit 1
fi
mkdir -p "$UPLOAD_DIR"

# ── القاعدة ───────────────────────────────────────────────────────
# الترحيل بابٌ لا يُتجاوز: فشله يعني قاعدةً لا تطابق الشفرة، فيوقف الإقلاع
# عمداً. والتعبئة لا تكرّر ما وُجد، وفشلها لا يُسقط الخادم — الترتيب نفسه
# على Render (‎render.yaml‎)
npm run db:migrate:deploy
npm run db:seed || echo "تعذّرت التعبئة — السبب أعلاه. الخادم يقلع رغمها" >&2

# ── صور الخادم القديم، أثناء الانتقال فقط ─────────────────────────
# ‎UPLOADS_SOURCE‎ عنوان الخادم القديم: الصور التي تذكرها القاعدة المنقولة
# تُسحب منه إلى القرص، وما وُجد سليماً لا يُعاد. وما تعذّر لا يوقف الإقلاع:
# يُذكر في السجلّ، وإعادة التشغيل تحاوله ثانية
if [ -n "${UPLOADS_SOURCE:-}" ]; then
  npm run --silent uploads:pull -- "$UPLOADS_SOURCE" \
    || echo "بعض الصور لم تُنقل — القائمة أعلاه. أعد تشغيل الخادم لمحاولتها ثانية" >&2
fi

# ── الخادم ────────────────────────────────────────────────────────
# بـnode مباشرةً لا بـ‎npm start‎: npm لا يمرّر إشارة الإيقاف إلى الخادم،
# فيخرج هو ويبقى الخادم حتى يُقتل قسراً. جرّبناه: npm خرج والخادم ظلّ يجيب.
# أمّا بـexec فيصير الخادم مكان هذا السكربت وتصله الإشارة نفسها، فيغلق
# الطلبات والقاعدة بهدوء
exec node --import tsx src/server.ts
